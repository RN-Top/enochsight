def generate_3d_model_from_api(prompt, api_choice='tripo'):
    # The 'enochian_api_key' is now retrieved at the top of this cell, so it's directly available.
    # The 'global' keyword is not needed here as we are only reading the variable.

    needs_simulation = True
    generated_model = None

    if api_choice == 'tripo':
        if not enochian_api_key:
            print("Tripo AI API key (ENOCHIAN_API_KEY) not found in Colab Secrets. Falling back to simulation.")
        else:
            headers = {
                "Authorization": f"Bearer {enochian_api_key}",
                "Content-Type": "application/json"
            }
            payload = {
                "prompt": prompt,
                "workflow_id": "txt2model" # Assuming a default workflow ID for text-to-model
            }
            try:
                print(f"Attempting to generate model with Tripo AI API for prompt: {prompt[:50]}...")
                # 1. Start generation task
                response = requests.post(f"{TRIPO_API_BASE_URL}/task", json=payload, headers=headers, timeout=30)
                response.raise_for_status() # Raise an exception for HTTP errors
                task_id = response.json().get('data', {}).get('task_id')

                if task_id:
                    print(f"Tripo AI API task started: {task_id}. Polling for result...")
                    # 2. Poll for task status
                    max_polls = 60 # Poll for up to 5 minutes (60 * 5s)
                    for _ in range(max_polls):
                        time.sleep(5) # Wait 5 seconds between polls
                        status_response = requests.get(f"{TRIPO_API_BASE_URL}/task/{task_id}", headers=headers, timeout=30)
                        status_response.raise_for_status()
                        status_data = status_response.json().get('data', {})

                        current_status = status_data.get('status')
                        if current_status == 'succeeded':
                            model_url = status_data.get('outputs', {}).get('model_url')
                            if model_url:
                                print(f"Model generation completed. Downloading from: {model_url}")
                                model_data = requests.get(model_url, timeout=60).content
                                generated_model = trimesh.load(file_obj=io.BytesIO(model_data), file_type='obj')
                                needs_simulation = False # API call was successful
                                break # Exit polling loop
                            else:
                                print("Tripo AI API completed but no model_url found. Falling back to simulation.")
                                break
                        elif current_status == 'failed':
                            print(f"Tripo AI API model generation failed: {status_data.get('msg', 'Unknown error')}. Falling back to simulation.")
                            break
                        else:
                            print(f"Tripo AI API task {task_id} status: {current_status}. Polling again...")
                    else: # This else block executes if the loop completes without a break (i.e., timed out)
                        print("Tripo AI API polling timed out. Falling back to simulation.")

                else:
                    print(f"Tripo AI API failed to start task: {response.json().get('msg', 'Unknown error')}. Falling back to simulation.")

            except requests.exceptions.RequestException as req_err:
                print(f"Network or API request error with Tripo AI: {req_err}. Falling back to simulation.")
